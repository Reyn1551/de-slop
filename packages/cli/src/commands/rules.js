import { writeFileSync } from 'node:fs';
import { rulesByModule, RULES_CATALOG } from '@de-slop/core';
import { parseArgs } from '../args.js';

export const help = `de-slop rules — list every rule, or regenerate docs/RULES.md

Usage: de-slop rules [options]

Prints the rule catalog: id, severity, and what the rule catches. With --write,
regenerates docs/RULES.md from the same catalog so the documentation cannot
drift from the code.

Options:
  --module <name>  Only list one module (slop-scanner, ux-guard, ...)
  --json           Print machine-readable JSON
  --write [path]   Write the Markdown reference (default: docs/RULES.md)
  --help           Show this help
`;

function markdown() {
  const lines = [];
  lines.push('# Rule reference');
  lines.push('');
  lines.push(`Every rule de-slop registers: ${RULES_CATALOG.length} in total.`);
  lines.push('');
  lines.push('Generated by `de-slop rules --write` from `packages/core/src/rules-catalog.ts`.');
  lines.push('A test fails when a registered rule has no entry here, so this page stays complete.');
  lines.push('');
  lines.push('Severity: `error` fails the build and marks a provable defect. `warning` reports a pattern that needs a human decision.');
  lines.push('');

  for (const group of rulesByModule()) {
    lines.push(`## ${group.module}`);
    lines.push('');
    lines.push('| Rule | Severity | Catches |');
    lines.push('|---|---|---|');
    for (const rule of group.rules) {
      lines.push(`| \`${rule.id}\` | ${rule.severity} | ${rule.description} |`);
    }
    lines.push('');
  }

  lines.push('## Selecting rules');
  lines.push('');
  lines.push('`--rules` takes a comma-separated list of ids and applies to every detector:');
  lines.push('');
  lines.push('```bash');
  lines.push('de-slop check . --rules no-chatbot-residue,no-plaintext-remote');
  lines.push('```');
  lines.push('');
  lines.push('The same list can live in `.desloprc.json` under `rules`, `prose`, or `ux`.');
  lines.push('');

  return `${lines.join('\n')}\n`;
}

export default async function rules(argv) {
  const { options } = parseArgs(argv);
  const module = typeof options.module === 'string' ? options.module : undefined;
  const groups = rulesByModule().filter((group) => module === undefined || group.module === module);

  if (groups.length === 0) {
    console.error(`de-slop rules: no module named '${module}'`);
    return 1;
  }

  if (options.write !== undefined) {
    const target = typeof options.write === 'string' ? options.write : 'docs/RULES.md';
    writeFileSync(target, markdown(), 'utf8');
    console.log(`de-slop rules: wrote ${target} (${RULES_CATALOG.length} rules)`);
    return 0;
  }

  if (options.json) {
    console.log(JSON.stringify(groups, null, 2));
    return 0;
  }

  for (const group of groups) {
    console.log(`${group.module} (${group.rules.length})`);
    for (const rule of group.rules) {
      const marker = rule.severity === 'error' ? 'error  ' : 'warning';
      console.log(`  ${marker} ${rule.id.padEnd(34)} ${rule.description}`);
    }
  }
  return 0;
}
